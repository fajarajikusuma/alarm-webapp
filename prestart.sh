#!/bin/bash
# ============================================================
# Web Alarm — Pre-start script (dijalankan sebagai root)
# Menangani inisialisasi hardware audio, unmuting, dan dmix
# ============================================================
set -e
LOG_PREFIX="[web-alarm prestart]"
log() { echo "$LOG_PREFIX $*"; }

log "====== START $(date) ======"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DB_FILE="$SCRIPT_DIR/instance/alarm.db"
UPLOAD_DIR="$SCRIPT_DIR/static/uploads/audios"

# ── 1. Disable ALSA plugin configs yang crash tanpa X11/JACK session ──
ALSA_CONF_DIR="/etc/alsa/conf.d"
DISABLE_CONFS="50-jack.conf 50-pulseaudio.conf 99-pulse.conf 99-pulseaudio-default.conf"
for conf in $DISABLE_CONFS; do
    if [ -f "$ALSA_CONF_DIR/$conf" ]; then
        mv "$ALSA_CONF_DIR/$conf" "$ALSA_CONF_DIR/${conf}.disabled"
        log "Disabled $conf"
    fi
done

# Bersihkan JACK shared memory (stale lock dari session sebelumnya)
rm -rf /dev/shm/jack_db-* /dev/shm/jack-* 2>/dev/null || true
log "Cleared stale JACK shm"

# ── 2. Load kernel modules audio ────────────────────────────
for mod in snd snd-pcm snd-usb-audio snd-hda-intel; do
    modprobe "$mod" 2>/dev/null || true
done
log "Kernel modules loaded"

# ── 3. Tunggu audio device siap ─────────────────────────────
log "Waiting for audio device..."
MAX_WAIT=30
WAITED=0
while [ $WAITED -lt $MAX_WAIT ]; do
    if [ -f /proc/asound/cards ] && grep -qE "^\s*[0-9]" /proc/asound/cards 2>/dev/null; then
        log "Audio card found after ${WAITED}s"
        break
    fi
    sleep 1
    WAITED=$((WAITED + 1))
done
if [ $WAITED -ge $MAX_WAIT ]; then
    log "WARNING: Audio device not detected after ${MAX_WAIT}s — continuing anyway"
fi

# ── 4. Fix /dev/snd permissions (world-rw) ──────────────────
if [ -d /dev/snd ]; then
    chmod -R o+rw /dev/snd 2>/dev/null || true
    log "/dev/snd permissions set to world-rw"
else
    log "WARNING: /dev/snd not found"
fi

# ── 5. Deteksi kartu suara (Prioritas: USB Audio, fallback: card 0) ──
CARD_SHORT=$(awk '/^\s*[0-9]/{
    if (match($0, /\[([^] ]+)/, a)) {
        if (tolower($0) ~ /usb/) { print a[1]; exit }
        if (!first) { first = a[1] }
    }
} END { if (!CARD_SHORT && first) print first }' /proc/asound/cards 2>/dev/null)

CARD_NUM=$(grep -oP '^\s*\K\d+' /proc/asound/cards 2>/dev/null | head -1)

if [ -n "$CARD_SHORT" ]; then
    ALSA_CARD_CTL="$CARD_SHORT"
    log "Using audio card: $CARD_SHORT"
elif [ -n "$CARD_NUM" ]; then
    ALSA_CARD_CTL="$CARD_NUM"
    log "Using card index: $CARD_NUM"
else
    ALSA_CARD_CTL="0"
    log "WARNING: no card found, defaulting to 0"
fi

# Tulis /etc/asound.conf dengan dmix (Direct Mixing)
# Ini mencegah error "Device or resource busy" jika beberapa proses memutar suara
cat > /etc/asound.conf << ASOUND
# Web Alarm — auto-generated by prestart.sh with dmix
pcm.!default {
    type plug
    slave.pcm "dmixer"
}

pcm.dmixer {
    type dmix
    ipc_key 1024
    ipc_perm 0666
    slave {
        pcm "hw:${ALSA_CARD_CTL},0"
        period_time 0
        period_size 1024
        buffer_size 4096
        rate 44100
    }
    bindings {
        0 0
        1 1
    }
}

ctl.!default {
    type hw
    card ${ALSA_CARD_CTL}
}
ASOUND
log "/etc/asound.conf written (card=${ALSA_CARD_CTL}, dmix enabled)"

# ── 6. Unmute dan Set Volume Hardware ───────────────────────
SAVED_VOL=""
if command -v sqlite3 >/dev/null 2>&1 && [ -f "$DB_FILE" ]; then
    SAVED_VOL=$(sqlite3 "$DB_FILE" "SELECT volume FROM audio_settings WHERE id=1;" 2>/dev/null || true)
    log "Volume from DB: ${SAVED_VOL:-not found}"
fi

if [ -n "$SAVED_VOL" ] && [ "$SAVED_VOL" -gt 0 ] 2>/dev/null; then
    TARGET_VOL="${SAVED_VOL}%"
else
    TARGET_VOL="80%"
fi

# Penting: Unmute dan set volume pada semua kontrol umum (Speaker, Master, PCM, Headphone)
# Setelah reboot / mati lampu, Linux default ke status MUTE [off]
for ctrl in Speaker Master PCM Headphone Playback; do
    amixer -c "$ALSA_CARD_CTL" sset "$ctrl" unmute 2>/dev/null || true
    if [ -n "$TARGET_VOL" ]; then
        amixer -c "$ALSA_CARD_CTL" sset "$ctrl" "$TARGET_VOL" 2>/dev/null || true
    fi
done
log "Audio unmuted and volume targeted to $TARGET_VOL"

# ── 7. Pastikan direktori upload ada ────────────────────────
mkdir -p "$UPLOAD_DIR"
# Ambil user pemilik script
DIR_OWNER=$(stat -c '%U:%G' "$SCRIPT_DIR" 2>/dev/null || echo "adminlh:adminlh")
chown -R "$DIR_OWNER" "$SCRIPT_DIR/static" 2>/dev/null || true
log "Upload directory ready ($UPLOAD_DIR)"

# ── 8. Bersihkan zombie player dari boot sebelumnya ──────────
pkill -9 mpv 2>/dev/null || true
pkill -9 mpg123 2>/dev/null || true
pkill -9 ffplay 2>/dev/null || true
log "Cleared any stale audio player processes"

log "====== DONE — Starting Flask ======"
